def classify(text):
    for cat, rx in RULES:
        if rx.search(text):
            return cat
    return None


def norm(s):
    s = re.sub(r"\s+", "", s)
    s = re.sub(r"[ー一―－-]+\s*\d+\s*[ー一―－-]+", "", s)  # ページ番号
    return re.sub(r"[、，,。．.・:：;；()（）「」\[\]［］〔〕]", "", s)


def grams(s, n=3):
    return {s[i:i + n] for i in range(max(1, len(s) - n + 1))}


def parse_exam(dirpath):
    pages = sorted(pathlib.Path(dirpath).glob("p-*.txt"), key=lambda p: int(p.stem.split("-")[1]))
    text = "\n".join(p.read_text(encoding="utf-8") for p in pages)
    # 「問1」「問 12」で始まる行で区切る。OCR では「問」が「間」に、10 が 19 のように
    # 0 が 9 になりやすいので、直前の番号から期待される番号と照合して補正する。
    # 見出しが読み取れなかった問題は直前の問題に含まれる（件数は missing に記録）。
    marks = list(re.finditer(r"(?m)^\s*[問間]\s*([0-9OIl]{1,2})\s", text))
    qs = {}
    expect = 1
    for k, m in enumerate(marks):
        raw = m.group(1).replace("O", "0").replace("I", "1").replace("l", "1")
        c = int(raw)
        if c != expect and expect % 10 == 0 and c == expect + 9:
            c = expect  # 10→19, 20→29 …
        if c < expect or c > expect + 3:
            continue  # 本文中の「問」など誤検出
        end = marks[k + 1].start() if k + 1 < len(marks) else len(text)
        qs[c] = text[m.end():end].strip()
        expect = c + 1
    return qs


def main():
    root = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    items = []
    for d in sorted(root.iterdir()):
        m = re.search(r"(\d{8})", d.name)
        if not m:
            continue
        exam = m.group(1)
        for no, body in sorted(parse_exam(d).items()):
            stem = re.split(r"\n\s*ア\s", body, maxsplit=1)[0]
            items.append({"exam": exam, "no": no, "text": body, "stem": stem, "cat": classify(stem) or classify(body)})

    # 同一問題（再出題）のクラスタリング：選択肢を含む問題全文の文字3-gramの Jaccard 係数。
    # 問題文だけだと「〜の説明はどれか」のような短い問題が別問題同士でつながるため全文で比べる。
    # 同じ回の問題同士は同一問題とみなさない（クラスタに同じ回が2つ入らないようにする）。
    g = [grams(norm(it["text"])) for it in items]
    parent = list(range(len(items)))
    exams_of = {i: {it["exam"]} for i, it in enumerate(items)}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    index = defaultdict(set)
    for i, s in enumerate(g):
        for t in s:
            index[t].add(i)
    pairs = []
    for i, s in enumerate(g):
        cand = Counter()
        for t in s:
            if len(index[t]) > 200:
                continue  # 頻出しすぎる3-gramは手掛かりにならない
            for j in index[t]:
                if j > i:
                    cand[j] += 1
        for j, c in cand.items():
            if c < 0.4 * min(len(s), len(g[j])):
                continue
            jac = len(s & g[j]) / len(s | g[j])
            if jac >= 0.5:
                pairs.append((jac, i, j))
    for jac, i, j in sorted(pairs, reverse=True):
        ri, rj = find(i), find(j)
        if ri == rj or exams_of[ri] & exams_of[rj]:
            continue
        parent[rj] = ri
        exams_of[ri] |= exams_of.pop(rj)
    for i, it in enumerate(items):
        it["cluster"] = find(i)

    out.write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")
    exams = sorted({it["exam"] for it in items})
    print("exams", len(exams), "questions", len(items))
    for e in exams:
        n = sum(1 for it in items if it["exam"] == e)
        print(" ", e, n)
    print("unclassified", sum(1 for it in items if not it["cat"]))
    print(Counter(it["cat"] for it in items).most_common())
    sizes = Counter(it["cluster"] for it in items)
    print("repeated clusters", sum(1 for c in sizes.values() if c > 1), "max", max(sizes.values()))


if __name__ == "__main__":
    main()
